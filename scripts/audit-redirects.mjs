#!/usr/bin/env node
/**
 * Lighthouse Campus — 301 redirect map + inbound-link audit.
 *
 * Scans every route for permanent (301) redirects, records WHY each one
 * exists (the doc comment above the route), then scans the whole source tree
 * for links that still point at a redirect source instead of its final
 * destination.
 *
 *   FAIL · a link (related block, <SmartLink to>, href, nav, sitemap)
 *          targets a 301 hop instead of the canonical URL
 *   FAIL · a redirect chain (301 -> 301) or a redirect to a missing route
 *
 * Writes:
 *   src/data/redirects.generated.ts  — data for the /internal/redirects board
 *   reports/redirects-report.md      — supervisor report
 *
 *   node scripts/audit-redirects.mjs
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync, statSync } from "node:fs";
import { join } from "node:path";

const ROUTES_DIR = "src/routes";
const SRC_DIR = "src";
const REPORT_PATH = "reports/redirects-report.md";
const DATA_PATH = "src/data/redirects.generated.ts";

const walkDir = (dir) =>
  readdirSync(dir).flatMap((entry) => {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) return walkDir(full);
    return /\.(tsx?|mjs|json|txt)$/.test(entry) && entry !== "routeTree.gen.ts" ? [full] : [];
  });

const routeFiles = walkDir(ROUTES_DIR).filter((f) => /\.tsx?$/.test(f));
const toUrl = (id) => id.replace(/_\//g, "/").replace(/\/$/, "") || "/";
const normalise = (t) => (t.split("#")[0].split("?")[0].replace(/\/$/, "") || "/");

/* ---------------------------------------------------------- discover routes */
const routeIds = new Set();
const redirects = []; // { from, to, statusCode, reason, file }

for (const file of routeFiles) {
  const src = readFileSync(file, "utf8");
  const m = src.match(/createFileRoute\(\s*["']([^"']+)["']\s*\)/);
  if (!m) continue;
  const id = toUrl(m[1]);
  if (id.startsWith("/api")) continue;
  routeIds.add(id);

  const r = src.match(/redirect\(\s*\{[^}]*to:\s*["']([^"']+)["'][^}]*\}/);
  if (!r || !/beforeLoad/.test(src)) continue;
  const status = src.match(/statusCode:\s*(\d{3})/);
  const doc = src.match(/\/\*\*([\s\S]*?)\*\//);
  const reason = doc
    ? doc[1]
        .split("\n")
        .map((l) => l.replace(/^\s*\*\s?/, "").trim())
        .filter((l) => l && !l.startsWith("@"))
        .join(" ")
    : "No documented purpose — add a doc comment above the route.";
  redirects.push({
    from: id,
    to: normalise(r[1]),
    statusCode: Number(status?.[1] ?? 302),
    reason,
    file,
  });
}
redirects.sort((a, b) => a.from.localeCompare(b.from));
const redirectMap = new Map(redirects.map((r) => [r.from, r.to]));

/* ------------------------------------------------------------- link scanning */
const linkFiles = walkDir(SRC_DIR).concat(["public/robots.txt"].filter((f) => {
  try { statSync(f); return true; } catch { return false; }
}));

const LINK_PATTERNS = [
  /\bto:\s*["']([^"']+)["']/g,
  /\bto=["']([^"']+)["']/g,
  /\bhref=["']([^"']+)["']/g,
  /\bpath:\s*["']([^"']+)["']/g,
  /https:\/\/(?:www\.)?lighthousecampus\.com(\/[^\s"'<)]*)/g,
];

const inbound = new Map(redirects.map((r) => [r.from, []])); // redirect -> [{file,line}]
for (const file of linkFiles) {
  if (redirects.some((r) => r.file === file)) continue; // the redirect route itself
  const src = readFileSync(file, "utf8");
  const lines = src.split("\n");
  lines.forEach((line, i) => {
    for (const pattern of LINK_PATTERNS) {
      pattern.lastIndex = 0;
      let m;
      while ((m = pattern.exec(line))) {
        const target = normalise(m[1]);
        if (redirectMap.has(target)) inbound.get(target).push({ file, line: i + 1 });
      }
    }
  });
}

/* ----------------------------------------------------------------- failures */
const failures = [];
for (const r of redirects) {
  if (!routeIds.has(r.to)) failures.push(`Broken redirect — ${r.from} -> ${r.to} (destination route does not exist)`);
  if (redirectMap.has(r.to)) failures.push(`Redirect chain — ${r.from} -> ${r.to} -> ${redirectMap.get(r.to)}; point at the final page`);
  if (r.statusCode !== 301) failures.push(`Non-permanent redirect — ${r.from} uses ${r.statusCode}; consolidation redirects must be 301`);
}
for (const [from, refs] of inbound) {
  for (const ref of refs) {
    failures.push(`Link to redirect — ${ref.file}:${ref.line} points at ${from}; link directly to ${redirectMap.get(from)}`);
  }
}

/* ------------------------------------------------------------ generated data */
const generatedAt = new Date().toISOString();
const data = `// AUTO-GENERATED by scripts/audit-redirects.mjs — do not edit by hand.
export type RedirectRecord = {
  from: string;
  to: string;
  statusCode: number;
  reason: string;
  file: string;
  inboundLinks: { file: string; line: number }[];
};

export const redirectsGeneratedAt = ${JSON.stringify(generatedAt)};

export const redirectRecords: RedirectRecord[] = ${JSON.stringify(
  redirects.map((r) => ({ ...r, inboundLinks: inbound.get(r.from) })),
  null,
  2,
)};

export const redirectIssues: string[] = ${JSON.stringify(failures, null, 2)};
`;
mkdirSync("src/data", { recursive: true });
writeFileSync(DATA_PATH, data);

/* --------------------------------------------------------- supervisor report */
const stamp = generatedAt.replace("T", " ").slice(0, 16) + " UTC";
const list = (arr) => (arr.length ? arr.map((x) => `- ${x}`).join("\n") : "- None");
const report = `# 301 Redirects — Supervisor Report
_Generated ${stamp} · لوحة تحويلات 301 والروابط التي تشير إليها_

## Summary / الملخص
| Metric | Value |
| --- | --- |
| Redirects mapped | ${redirects.length} |
| Files scanned for links | ${linkFiles.length} |
| Links pointing at a redirect | ${[...inbound.values()].reduce((n, v) => n + v.length, 0)} |
| Blocking issues | ${failures.length} |
| Status | ${failures.length ? "❌ FAILED" : "✅ PASSED"} |

## Redirect map / خريطة التحويلات
${redirects.length
    ? redirects
        .map(
          (r) =>
            `- \`${r.from}\` → \`${r.to}\` (${r.statusCode}) — ${r.reason}\n  · inbound links: ${
              inbound.get(r.from).length
                ? inbound.get(r.from).map((x) => `${x.file}:${x.line}`).join(", ")
                : "none"
            }`,
        )
        .join("\n")
    : "- None"}

## Blocking issues / مخالفات
${list(failures)}

---
Rule: internal links must target the final canonical page. Redirects exist for
external/legacy traffic only.
`;
mkdirSync("reports", { recursive: true });
writeFileSync(REPORT_PATH, report);

console.log(`Redirect map written to ${DATA_PATH}`);
console.log(`Report written to ${REPORT_PATH}`);
for (const r of redirects) console.log(`  · ${r.from} -> ${r.to} (${r.statusCode})`);
if (failures.length) {
  console.error(`\n✖ Redirect audit failed — ${failures.length} issue(s):\n`);
  for (const f of failures) console.error("  • " + f);
  process.exit(1);
}
console.log(`\n✔ Redirect audit passed — ${redirects.length} redirects, no internal links pointing at a hop.`);
